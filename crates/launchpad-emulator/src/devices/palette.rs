/// Returns the colour for a palette entry, or `None` for an entry of 128 or above.
#[must_use]
pub fn get(entry: u8) -> Option<Rgb> {
    let [r, g, b] = *PALETTE.get(entry as usize)?;
    Some(Rgb { r, g, b })
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    #[test]
    fn entry_zero_is_unlit() {
        assert_eq!(get(0).unwrap(), Rgb::BLACK);
    }

    #[test]
    fn primaries_are_saturated() {
        assert_eq!(
            get(3).unwrap(),
            Rgb {
                r: 255,
                g: 255,
                b: 255
            }
        );
        assert_eq!(get(5).unwrap(), Rgb { r: 255, g: 0, b: 0 });
        assert_eq!(get(21).unwrap(), Rgb { r: 0, g: 255, b: 0 });
        assert_eq!(get(45).unwrap(), Rgb { r: 0, g: 0, b: 255 });
    }

    #[test]
    fn entries_above_the_palette_are_rejected() {
        assert!(get(LEN).is_none());
        assert!(get(255).is_none());
    }
}
